#!/usr/bin/env python3
"""
build_web.py - turn web/index.html into temperature_server_src/web_page.h

Implements: REQ-WEB-02 (single embedded, gzip-compressed page) and the size
budget of the implementation plan (gzip <= 40 KB).

What it does:
  1. reads web/index.html
  2. strips only SAFE things: HTML comments, comment-only lines, indentation,
     blank lines (it never rewrites code, so it cannot break the JavaScript)
  3. gzips the result (deterministic: mtime 0)
  4. writes a C header holding the bytes in PROGMEM

Usage:  python3 tools/build_web.py
"""

import gzip
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "index.html"
DST = ROOT / "temperature_server_src" / "web_page.h"
GZIP_BUDGET = 40 * 1024


def minify(text: str) -> str:
    """Remove comments and whitespace that cannot change behaviour."""
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)        # HTML comments
    text = re.sub(r"^\s*/\*.*?\*/\s*$", "", text, flags=re.S | re.M)  # whole-line /* */ blocks
    lines = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("//"):          # blank or comment-only line
            continue
        lines.append(stripped)
    return "\n".join(lines) + "\n"


def to_c_array(data: bytes) -> str:
    """Format bytes as a C initialiser, 16 per line."""
    rows = []
    for i in range(0, len(data), 16):
        rows.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]))
    return ",\n".join(rows)


def main() -> int:
    if not SRC.exists():
        print(f"error: {SRC} not found", file=sys.stderr)
        return 1

    html = minify(SRC.read_text(encoding="utf-8"))
    packed = gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)

    DST.write_text(
        "/**\n"
        " * @file web_page.h\n"
        " * @brief GENERATED by tools/build_web.py from web/index.html - do not edit.\n"
        " *\n"
        " * The complete web UI as one gzip-compressed page (REQ-WEB-02).\n"
        " */\n\n"
        "#ifndef WEB_PAGE_H\n#define WEB_PAGE_H\n\n"
        "#include <Arduino.h>\n\n"
        f"// Source: {len(html)} bytes, gzip: {len(packed)} bytes\n"
        f"const size_t web_page_gz_len = {len(packed)};\n"
        "const uint8_t web_page_gz[] PROGMEM = {\n"
        f"{to_c_array(packed)}\n"
        "};\n\n"
        "#endif  // WEB_PAGE_H\n",
        encoding="utf-8",
    )

    print(f"web/index.html: {SRC.stat().st_size} B -> minified {len(html)} B -> gzip {len(packed)} B")
    if len(packed) > GZIP_BUDGET:
        print(f"warning: gzip size above the {GZIP_BUDGET} B budget", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
