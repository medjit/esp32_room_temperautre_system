#!/usr/bin/env python3
"""
traceability.py - builds traceability.md: for every requirement, where it is implemented.

The firmware, the web page and the tests tag their code with the identifiers they
implement (REQ-xxx-nn, also ranges like "REQ-RX-01 .. REQ-RX-06" and "REQ-CHG-01/02").
This script reads requirements.md and those tags and prints one table row per
requirement, so nothing can silently go untracked.

Usage:  python3 tools/traceability.py          (writes traceability.md)
Exit code 1 if a requirement has no reference at all.
"""

import collections
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = sorted(
    [p for p in (ROOT / "temperature_server_src").glob("*.*") if p.name != "web_page.h"]
    + [ROOT / "web" / "index.html", ROOT / "tools" / "build_web.py", ROOT / "tools" / "mock_server.py"]
)
TESTS = [ROOT / "test" / "test_logic.cpp", ROOT / "tools" / "test_sender" / "test_sender.ino"]


def expand(text: str) -> set:
    """All requirement ids mentioned in a text, expanding ranges and slash lists."""
    found = set()
    for m in re.finditer(r"REQ-([A-Z]+)-(\d+)\s*(?:\.\.|-|\u2013)\s*(?:REQ-[A-Z]+-)?(\d+)", text):
        for n in range(int(m.group(2)), int(m.group(3)) + 1):
            found.add(f"REQ-{m.group(1)}-{n:02d}")
    for m in re.finditer(r"REQ-([A-Z]+)-(\d+)((?:/\d+)*)", text):
        found.add(f"REQ-{m.group(1)}-{int(m.group(2)):02d}")
        for n in [x for x in m.group(3).split("/") if x]:
            found.add(f"REQ-{m.group(1)}-{int(n):02d}")
    return found


def main() -> int:
    req_text = (ROOT / "requirements.md").read_text()
    # id -> first sentence of the requirement
    titles = {}
    for m in re.finditer(r"\*\*(REQ-[A-Z]+-\d+)\*\* \u2014 (.+)", req_text):
        titles[m.group(1)] = m.group(2).split(". ")[0].strip()
    ids = sorted(titles, key=lambda i: (i.split("-")[1], int(i.split("-")[2])))

    code, tests = collections.defaultdict(set), collections.defaultdict(set)
    for p in SOURCES:
        for r in expand(p.read_text()):
            code[r].add(p.name)
    for p in TESTS:
        for r in expand(p.read_text()):
            tests[r].add(p.name)

    lines = [
        "# Requirements traceability (generated)",
        "",
        "Generated by `tools/traceability.py` from the `REQ-xxx` tags in the code. Do not edit by hand.",
        "",
        "| Requirement | Summary | Implemented in | Tests / tools |",
        "|---|---|---|---|",
    ]
    missing = []
    for i in ids:
        if not code[i]:
            missing.append(i)
        summary = titles[i].replace("|", "/")[:90]
        lines.append(f"| {i} | {summary} | {', '.join(sorted(code[i])) or '**MISSING**'} | {', '.join(sorted(tests[i])) or '-'} |")

    (ROOT / "traceability.md").write_text("\n".join(lines) + "\n")
    print(f"{len(ids)} requirements, {len(missing)} without a reference {missing if missing else ''}")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
