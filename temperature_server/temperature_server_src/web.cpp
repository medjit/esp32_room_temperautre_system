// PIN protection
// ---------------------------------------------------------------------------

static uint8_t  s_pinFails    = 0;
static uint32_t s_lockUntilMs = 0;        // 0 = not locked

/**
 * Compare a PIN with the stored one without leaking, through timing, how many
 * leading characters were right. Implements: REQ-SEC-01.
 */
static bool pinMatches(const char *given) {
    const char *pin = g_settings.pin;
    uint8_t diff = (strlen(given) > 8) ? 1 : 0;
    for (size_t i = 0; i < 8; i++) {
        const char a = (i < strlen(given)) ? given[i] : 0;
        const char b = (i < strlen(pin))   ? pin[i]   : 0;
        diff |= (uint8_t)(a ^ b);
    }
    return diff == 0;
}

/**
 * Check the X-Pin header of a request. Sends the error response itself.
 *
 * Implements: REQ-SEC-01, REQ-SEC-02, REQ-WEB-08. After PIN_MAX_ATTEMPTS wrong
 * PINs in a row, every protected request is refused with 429 for
 * PIN_LOCKOUT_S seconds, for all clients.
 *
 * @return true if the request may proceed.
 */
static bool requirePin() {
    const uint32_t now = millis();

    if (s_lockUntilMs != 0) {
        if ((int32_t)(now - s_lockUntilMs) < 0) {
            sendError(429, "too many wrong PINs, try again later");
            return false;
        }
        s_lockUntilMs = 0;                  // lockout is over
        s_pinFails = 0;
    }

    if (pinMatches(s_server.header("X-Pin").c_str())) {
        s_pinFails = 0;
        return true;
    }
    if (++s_pinFails >= PIN_MAX_ATTEMPTS) {
        s_lockUntilMs = now + PIN_LOCKOUT_S * 1000UL;
        if (s_lockUntilMs == 0) s_lockUntilMs = 1;
        DBG_PRINTF("WEB: PIN lockout for %d s", PIN_LOCKOUT_S);
    }
    sendError(401, "wrong PIN");
    return false;
}

