/**
 * Register routes and start the server.
 * Implements: REQ-WEB-01. The X-Pin header must be listed to be readable.
 */
void webBegin() {
    static const char *kHeaders[] = {"X-Pin"};
    s_server.collectHeaders(kHeaders, 1);

    s_server.on("/",                   HTTP_GET,  handleRoot);
    s_server.on("/api/state",          HTTP_GET,  handleState);
    s_server.on("/api/history",        HTTP_GET,  handleHistory);
    s_server.on("/api/export.csv",     HTTP_GET,  handleExportCsv);
    s_server.on("/api/auth",           HTTP_POST, handleAuth);
    s_server.on("/api/wifi/scan",      HTTP_GET,  handleWifiScan);
    s_server.on("/api/wifi",           HTTP_POST, handleWifiSave);
    s_server.on("/api/node",           HTTP_POST, handleNodeEdit);
    s_server.on("/api/node/delete",    HTTP_POST, handleNodeDelete);
    s_server.on("/api/room",           HTTP_POST, handleRoom);
    s_server.on("/api/pin",            HTTP_POST, handlePinChange);
    s_server.on("/api/history/clear",  HTTP_POST, handleHistoryClear);
    s_server.on("/api/restart",        HTTP_POST, handleRestart);
    s_server.on("/api/factory-reset",  HTTP_POST, handleFactoryReset);
    s_server.onNotFound(handleNotFound);

    s_server.begin();
    DBG_PRINTF("WEB: server started on port 80");
}

/** Serve requests and carry out a scheduled restart / factory reset. */
void webTick(uint32_t nowMs) {
    s_server.handleClient();

    if (s_pending != ACT_NONE && (int32_t)(nowMs - s_pendingAtMs) >= 0) {
        if (s_pending == ACT_FACTORY_RESET) {
            storeFactoryReset();                 // never returns
        }
        snapshotSave();
        DBG_PRINTF("WEB: restarting on request");
        delay(100);
        ESP.restart();
    }
}
