/** Merged samples of the current history response (static: too big for the stack). */
static Sample s_histOut[HIST_API_MAX_POINTS];

/** Find the slot named by the `node` query argument, or send 404. @return slot index or -1. */
static int slotFromQuery() {
    long id;
    if (!argInt("node", 0, 255, &id)) { sendError(400, "node missing"); return -1; }
    const int idx = nodeFindIndex((uint8_t)id);
    if (idx < 0) sendError(404, "unknown node");
    return idx;
}

/**
 * GET /api/history?node=<id>&from=<ts>
 *
 * Implements: REQ-HIST-06, REQ-WEB-04. The answer holds parallel arrays, which
 * keeps it compact:  t = time, v = room temp (0.01 C or null), s = source
 * (0 none, 1 ds, 2 est), c = raw CPU temp, b = battery mV. `step` tells how
 * many stored samples were merged into each point (1 = no merging).
 */
static void handleHistory() {
    touch();
    const int idx = slotFromQuery();
    if (idx < 0) return;
    const NodeSlot &n = g_nodes[idx];

    // `from` is an unsigned 32-bit timestamp, so it is parsed on its own (argInt() uses long).
    uint32_t from = 0;
    if (s_server.hasArg("from")) from = (uint32_t)strtoul(s_server.arg("from").c_str(), nullptr, 10);

    uint16_t step = 1;
    const uint16_t count = histDownsample(n.hist, from, HIST_API_MAX_POINTS, s_histOut, &step);

    ChunkedOut out(s_server);
    out.begin("application/json");
    out.objStart();
    out.kNum("node", n.nodeId);
    out.kNum("step", step);
    out.kNum("sleep_s", (long)nodeSleepSeconds(n));
    out.kBool("time_valid", netTimeValid());
    out.kNum("now", (long)netStamp());

    out.key("t"); out.arrStart();
    for (uint16_t i = 0; i < count; i++) out.num((long)s_histOut[i].ts);
    out.arrEnd();

    out.key("v"); out.arrStart();
    for (uint16_t i = 0; i < count; i++) {
        if (s_histOut[i].room_cC == TEMP_INVALID) out.null(); else out.num(s_histOut[i].room_cC);
    }
    out.arrEnd();

    out.key("s"); out.arrStart();
    for (uint16_t i = 0; i < count; i++) out.num(sampleSource(s_histOut[i]));
    out.arrEnd();

    out.key("c"); out.arrStart();
    for (uint16_t i = 0; i < count; i++) {
        if (s_histOut[i].cpu_cC == TEMP_INVALID) out.null(); else out.num(s_histOut[i].cpu_cC);
    }
    out.arrEnd();

    out.key("b"); out.arrStart();
    for (uint16_t i = 0; i < count; i++) out.num(s_histOut[i].bat_mv);
    out.arrEnd();

    out.objEnd();
    out.finish();
}

/**
 * GET /api/export.csv?node=<id>   (MAY requirement, REQ-WEB-04)
 *
 * One line per stored sample, no merging. The `utc` column is empty for
 * samples recorded before the clock was known; `ts` then holds virtual seconds.
 */
static void handleExportCsv() {
    touch();
    const int idx = slotFromQuery();
    if (idx < 0) return;
    const NodeSlot &n = g_nodes[idx];

    ChunkedOut out(s_server);
    out.begin("text/csv");
    out.raw("ts,utc,room_C,source,cpu_C,battery_mV,battery_state,charging\n");

    for (uint16_t i = 0; i < n.hist.count; i++) {
        const Sample &s = histAt(n.hist, i);

        char utc[24] = "";
        if (!stampIsVirtual(s.ts)) {
            const time_t t = (time_t)s.ts;
            struct tm tmv;
            gmtime_r(&t, &tmv);
            strftime(utc, sizeof(utc), "%Y-%m-%dT%H:%M:%SZ", &tmv);
        }
        char room[12] = "", cpu[12] = "";
        if (s.room_cC != TEMP_INVALID) snprintf(room, sizeof(room), "%.2f", s.room_cC / 100.0);
        if (s.cpu_cC  != TEMP_INVALID) snprintf(cpu,  sizeof(cpu),  "%.2f", s.cpu_cC / 100.0);

        char line[120];
        const int len = snprintf(line, sizeof(line), "%lu,%s,%s,%u,%s,%u,%u,%u\n",
                                 (unsigned long)s.ts, utc, room, (unsigned)sampleSource(s), cpu,
                                 (unsigned)s.bat_mv, (unsigned)sampleBatState(s),
                                 sampleCharging(s) ? 1u : 0u);
        out.raw(line, (size_t)len);
    }
    out.finish();
}

