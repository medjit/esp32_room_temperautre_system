// ---------------------------------------------------------------------------
// Chunked output writer
// ---------------------------------------------------------------------------

/**
 * Writes JSON (or any text) to the client in small chunks.
 *
 * It keeps a small buffer; whenever the buffer is full it is sent with
 * HTTP chunked transfer encoding. JSON commas are inserted automatically:
 * just call key()/value functions in order.
 *
 * Example:  out.objStart(); out.key("n"); out.num(5); out.objEnd();  ->  {"n":5}
 */
class ChunkedOut {
public:
    explicit ChunkedOut(WebServer &srv) : m_srv(srv) {}

    /** Send the response headers. Must be called once before anything else. */
    void begin(const char *contentType) {
        m_srv.sendHeader("Cache-Control", "no-store");
        m_srv.setContentLength(CONTENT_LENGTH_UNKNOWN);
        m_srv.send(200, contentType, "");
    }

    /** Flush the rest and end the chunked response. */
    void finish() {
        flush();
        m_srv.sendContent("");
    }

    // ---- plain text (used by the CSV export) ----
    void raw(const char *text, size_t len) {
        while (len > 0) {
            size_t room = CHUNK_SIZE - m_len;
            if (room == 0) { flush(); room = CHUNK_SIZE; }
            size_t take = len < room ? len : room;
            memcpy(m_buf + m_len, text, take);
            m_len += take; text += take; len -= take;
        }
    }
    void raw(const char *text) { raw(text, strlen(text)); }

    // ---- JSON structure ----
    void objStart() { beforeValue(); raw("{"); push(); }
    void objEnd()   { pop(); raw("}"); }
    void arrStart() { beforeValue(); raw("["); push(); }
    void arrEnd()   { pop(); raw("]"); }

    /** Write an object key. The next call must write its value. */
    void key(const char *name) {
        beforeValue();
        raw("\""); raw(name); raw("\":");
        m_afterKey = true;
    }

    // ---- JSON values ----
    void num(int64_t v) {
        beforeValue();
        char tmp[24];
        int n = snprintf(tmp, sizeof(tmp), "%lld", (long long)v);
        raw(tmp, (size_t)n);
    }
    void boolean(bool v) { beforeValue(); raw(v ? "true" : "false"); }
    void null()          { beforeValue(); raw("null"); }

    /** Write a string value with JSON escaping. */
    void str(const char *s) {
        beforeValue();
        raw("\"");
        for (; *s; s++) {
            const uint8_t c = (uint8_t)*s;
            if (c == '"' || c == '\\') { char e[2] = {'\\', (char)c}; raw(e, 2); }
            else if (c < 0x20)         { raw(" "); }                  // control chars become blanks
            else                       { raw(s, 1); }
        }
        raw("\"");
    }

    // ---- key + value shortcuts ----
    void kNum(const char *k, int64_t v)      { key(k); num(v); }
    void kBool(const char *k, bool v)        { key(k); boolean(v); }
    void kStr(const char *k, const char *v)  { key(k); str(v); }

private:
    static const size_t CHUNK_SIZE = 512;
    static const int    MAX_DEPTH  = 8;

    WebServer &m_srv;
    char       m_buf[CHUNK_SIZE];
    size_t     m_len = 0;
    bool       m_first[MAX_DEPTH + 1] = {true};   // "nothing written yet" per nesting level
    int        m_depth = 0;
    bool       m_afterKey = false;

    void flush() {
        if (m_len > 0) { m_srv.sendContent(m_buf, m_len); m_len = 0; }
    }
    /** Insert the comma between siblings, except directly after a key. */
    void beforeValue() {
        if (m_afterKey) { m_afterKey = false; return; }
        if (!m_first[m_depth]) raw(",");
        m_first[m_depth] = false;
    }
    void push() { if (m_depth < MAX_DEPTH) m_first[++m_depth] = true; }
    void pop()  { if (m_depth > 0) m_depth--; }
};

