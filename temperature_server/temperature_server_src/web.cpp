/**
 * Serve the embedded web page.
 * Implements: REQ-WEB-02. The page is stored gzip-compressed in flash and sent
 * as is; "no-cache" makes browsers pick up a new firmware's page.
 */
static void handleRoot() {
    touch();
    s_server.sendHeader("Content-Encoding", "gzip");
    s_server.sendHeader("Cache-Control", "no-cache");
    s_server.send_P(200, "text/html", (PGM_P)web_page_gz, web_page_gz_len);
}

/**
 * Anything unknown: in captive-portal mode send the browser to the setup page
 * (so phones open it automatically, REQ-UI-10), otherwise answer 404.
 */
static void handleNotFound() {
    touch();
    if (netCaptiveActive()) {
        s_server.sendHeader("Location", "http://" + WiFi.softAPIP().toString() + "/");
        s_server.send(302, "text/plain", "");
        return;
    }
    sendError(404, "not found");
}

