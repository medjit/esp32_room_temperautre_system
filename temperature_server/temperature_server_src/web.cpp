/** Write the "server" part of /api/state. Implements: REQ-WEB-05, REQ-NET-07. */
static void writeServerInfo(ChunkedOut &out) {
    out.key("server"); out.objStart();
    out.kNum("fw", SERVER_FW_VERSION);
    out.kNum("uptime_s", (long)(millis() / 1000UL));
    out.kNum("heap_free", (long)ESP.getFreeHeap());
    out.kNum("heap_min", (long)ESP.getMinFreeHeap());
    out.kBool("time_valid", netTimeValid());
    out.kNum("epoch", netTimeValid() ? (long)time(nullptr) : 0);
    out.kBool("pin_default", storePinIsDefault());
    out.kNum("max_nodes", MAX_NODES);
    out.kStr("hostname", MDNS_HOSTNAME ".local");

    out.key("wifi"); out.objStart();
    const bool sta = netStaConnected();
    out.kStr("mode", netModeName());
    out.kBool("connected", sta);
    out.kBool("has_credentials", netHasCredentials());
    out.kStr("ssid", sta ? WiFi.SSID().c_str() : g_settings.ssid);
    out.kStr("ip", (sta ? WiFi.localIP() : WiFi.softAPIP()).toString().c_str());
    out.kNum("channel", netChannel());
    out.kNum("rssi", sta ? WiFi.RSSI() : 0);
    out.kStr("ap_ssid", AP_SSID);
    out.objEnd();

    out.key("stats"); out.objStart();
    out.kNum("frames", (long)g_stats.frames);
    out.kNum("accepted", (long)g_stats.accepted);
    out.kNum("duplicates", (long)g_stats.duplicates);
    out.kNum("bad_len", (long)g_stats.badLen);
    out.kNum("bad_ver", (long)g_stats.badVer);
    out.kNum("bad_crc", (long)g_stats.badCrc);
    out.kNum("unknown", (long)g_stats.unknownNode);
    out.kNum("overflow", (long)g_stats.overflow);
    out.objEnd();

    out.key("unknown_ids"); out.arrStart();
    uint8_t ids[8];
    const uint8_t count = nodeUnknownIds(ids, sizeof(ids));
    for (uint8_t i = 0; i < count; i++) out.num(ids[i]);
    out.arrEnd();

    out.objEnd();
}

/** Write one node of /api/state. Implements: REQ-WEB-05, REQ-DATA-02..04. */
static void writeNode(ChunkedOut &out, const NodeSlot &n, uint32_t nowMs) {
    out.objStart();
    out.kNum("id", n.nodeId);
    out.kStr("name", n.name);
    out.kNum("corner", n.corner);
    out.kStr("status", statusName(n.status));
    out.kNum("cpu_offset_cC", n.cpuOffsetCc);
    out.kNum("sleep_s", (long)nodeSleepSeconds(n));
    out.kNum("stuck_after_s", (long)(stuckTimeoutMs(nodeSleepSeconds(n)) / 1000UL));
    out.kNum("rx", (long)n.rxCount);
    out.kNum("dups", (long)n.dupCount);
    out.kNum("crc_err", (long)n.crcErrCount);
    out.kBool("has_data", n.haveLast);

    if (n.haveLast) {
        const NodePacket &p = n.last;
        const RoomTemp t = pickTemperature(p, n.cpuOffsetCc);
        out.kNum("age_s", (long)((nowMs - n.lastRxMs) / 1000UL));
        if (t.src == SRC_NONE) { out.key("temp_cC"); out.null(); }
        else                   { out.kNum("temp_cC", t.cC); }
        out.kStr("src", t.src == SRC_DS ? "ds" : t.src == SRC_EST ? "est" : "none");
        if (p.cpu_temp_cC == TEMP_INVALID) { out.key("cpu_cC"); out.null(); }
        else                               { out.kNum("cpu_cC", p.cpu_temp_cC); }
        out.kNum("bat_mv", p.battery_mv);
        out.kNum("bat_state", p.battery_state);
        out.kNum("bat_pct", batteryPercent(p.battery_mv));
        out.kBool("charging", p.is_charging != 0);
        out.kNum("vbus_mv", p.vbus_mv);
        out.kNum("rssi", n.rssi);
        out.kNum("flags", p.status_flags);
        out.kNum("node_fw", p.fw_version);
        out.kNum("boot", (long)p.boot_count);
    }
    out.objEnd();
}

/** GET /api/state. Implements: REQ-WEB-04, REQ-WEB-05, REQ-UI-04. */
static void handleState() {
    touch();
    ChunkedOut out(s_server);
    out.begin("application/json");
    const uint32_t now = millis();

    out.objStart();
    writeServerInfo(out);
    out.kStr("room", g_settings.room);

    out.key("ui"); out.objStart();
    out.kNum("tmin", UI_TEMP_MIN_C);
    out.kNum("tmax", UI_TEMP_MAX_C);
    out.kNum("poll_s", UI_POLL_S);
    out.objEnd();

    out.key("nodes"); out.arrStart();
    for (int i = 0; i < MAX_NODES; i++) {
        if (g_nodes[i].used) writeNode(out, g_nodes[i], now);
    }
    out.arrEnd();
    out.objEnd();
    out.finish();
}

