/**
 * GET /api/wifi/scan[?start=1]   [PIN]
 *
 * Implements: REQ-WEB-04, REQ-WEB-07 (the scan runs asynchronously; the page
 * polls). A scan hops over all channels, so reception pauses briefly: it only
 * happens when the user asks for it with ?start=1 (REQ-NET-05 rationale).
 */
static void handleWifiScan() {
    touch();
    if (!requirePin()) return;

    if (s_server.hasArg("start") && WiFi.scanComplete() != WIFI_SCAN_RUNNING) {
        WiFi.scanDelete();
        netPrepareScan();
        WiFi.scanNetworks(true);                         // true = do not block
    }

    const int found = WiFi.scanComplete();
    ChunkedOut out(s_server);
    out.begin("application/json");
    out.objStart();
    out.kBool("scanning", found == WIFI_SCAN_RUNNING);

    out.key("networks"); out.arrStart();
    for (int i = 0; i < found && i < 20; i++) {
        if (WiFi.SSID(i).length() == 0) continue;        // hidden network
        out.objStart();
        out.kStr("ssid", WiFi.SSID(i).c_str());
        out.kNum("rssi", WiFi.RSSI(i));
        out.kNum("channel", WiFi.channel(i));
        out.kBool("secure", WiFi.encryptionType(i) != WIFI_AUTH_OPEN);
        out.objEnd();
    }
    out.arrEnd();
    out.objEnd();
    out.finish();
}

/**
 * POST /api/wifi  (ssid, pass)   [PIN]
 *
 * Implements: REQ-UI-09, REQ-UI-10. The credentials are stored and the server
 * starts joining the router at once; the page polls /api/state for the result.
 */
static void handleWifiSave() {
    touch();
    if (!requirePin()) return;

    const String ssid = s_server.arg("ssid");
    const String pass = s_server.arg("pass");
    if (ssid.length() < 1 || ssid.length() > 32) { sendError(400, "SSID must be 1-32 characters"); return; }
    if (pass.length() != 0 && (pass.length() < 8 || pass.length() > 64)) {
        sendError(400, "password must be 8-64 characters (or empty for an open network)");
        return;
    }

    strncpy(g_settings.ssid, ssid.c_str(), sizeof(g_settings.ssid) - 1);
    strncpy(g_settings.pass, pass.c_str(), sizeof(g_settings.pass) - 1);
    settingsSave();
    sendOk();                                            // answer BEFORE the radio changes
    netApplyCredentials();
}

