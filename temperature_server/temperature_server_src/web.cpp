/** Maximum accepted length of any form field (REQ-ERR-05). */
#define ARG_MAX_LEN 80

/**
 * Read an integer form/query argument and check its range.
 * @return true if the argument exists, is a number and lies within [lo, hi].
 */
static bool argInt(const char *name, long lo, long hi, long *out) {
    if (!s_server.hasArg(name)) return false;
    const String v = s_server.arg(name);
    if (v.length() == 0 || v.length() > 11) return false;

    char *end = nullptr;
    const long x = strtol(v.c_str(), &end, 10);
    if (*end != '\0' || x < lo || x > hi) return false;
    *out = x;
    return true;
}

/** @return true if the text consists only of ASCII digits and has 4..8 characters. */
static bool isValidPin(const String &s) {
    if (s.length() < 4 || s.length() > 8) return false;
    for (size_t i = 0; i < s.length(); i++) {
        if (s[i] < '0' || s[i] > '9') return false;
    }
    return true;
}

