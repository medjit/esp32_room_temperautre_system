/**
 * POST /api/node  (id, [name], [corner], [offset])   [PIN]
 * Implements: REQ-NODE-02, REQ-NODE-04. `offset` is the CPU offset in 0.01 C.
 */
static void handleNodeEdit() {
    touch();
    if (!requirePin()) return;

    long id;
    if (!argInt("id", 0, 255, &id)) { sendError(400, "id missing"); return; }
    const int idx = nodeFindIndex((uint8_t)id);
    if (idx < 0) { sendError(404, "unknown node"); return; }

    long v;
    if (s_server.hasArg("name")) {
        if (s_server.arg("name").length() > ARG_MAX_LEN) { sendError(400, "name too long"); return; }
        nodeSetName(idx, s_server.arg("name").c_str());
    }
    if (s_server.hasArg("corner")) {
        if (!argInt("corner", 0, 3, &v)) { sendError(400, "corner must be 0-3"); return; }
        nodeSetCorner(idx, (uint8_t)v);
    }
    if (s_server.hasArg("offset")) {
        if (!argInt("offset", -5000, 5000, &v)) { sendError(400, "offset out of range"); return; }
        g_nodes[idx].cpuOffsetCc = (int16_t)v;
    }

    // A corner swap changes another slot too: save them all (cheap, rare).
    for (int i = 0; i < MAX_NODES; i++) if (g_nodes[i].used) storeSaveNode(i);
    sendOk();
}

/** POST /api/node/delete  (id)   [PIN]. Implements: REQ-NODE-03. */
static void handleNodeDelete() {
    touch();
    if (!requirePin()) return;

    long id;
    if (!argInt("id", 0, 255, &id)) { sendError(400, "id missing"); return; }
    const int idx = nodeFindIndex((uint8_t)id);
    if (idx < 0) { sendError(404, "unknown node"); return; }

    nodeForget(idx);
    storeSaveNode(idx);                                  // stored as "free"
    storeMarkHistoryDirty();
    sendOk();
}

/** POST /api/room  (name)   [PIN]. Implements: REQ-UI-09. */
static void handleRoom() {
    touch();
    if (!requirePin()) return;

    const String name = s_server.arg("name");
    if (name.length() < 1 || name.length() > sizeof(g_settings.room) - 1) {
        sendError(400, "room name must be 1-24 characters");
        return;
    }
    memset(g_settings.room, 0, sizeof(g_settings.room));
    for (size_t i = 0; i < name.length(); i++) {
        g_settings.room[i] = ((uint8_t)name[i] < 0x20) ? ' ' : name[i];
    }
    settingsSave();
    sendOk();
}

/** POST /api/pin  (new)   [PIN]. Implements: REQ-SEC-01. */
static void handlePinChange() {
    touch();
    if (!requirePin()) return;

    const String fresh = s_server.arg("new");
    if (!isValidPin(fresh)) { sendError(400, "PIN must be 4-8 digits"); return; }

    strncpy(g_settings.pin, fresh.c_str(), sizeof(g_settings.pin) - 1);
    settingsSave();
    sendOk();
}

/** POST /api/auth   [PIN]: lets the page check a PIN before showing settings. */
static void handleAuth() {
    touch();
    if (requirePin()) sendOk();
}

/** POST /api/history/clear   [PIN]. Implements: REQ-HIST-07 (MAY). */
static void handleHistoryClear() {
    touch();
    if (!requirePin()) return;
    storeClearHistory();
    sendOk();
}

// ---------------------------------------------------------------------------
// Restart and factory reset (delayed so the answer can be delivered first)
// ---------------------------------------------------------------------------

enum PendingAction : uint8_t { ACT_NONE, ACT_RESTART, ACT_FACTORY_RESET };
static PendingAction s_pending      = ACT_NONE;
static uint32_t      s_pendingAtMs  = 0;

static void schedule(PendingAction a) {
    s_pending = a;
    s_pendingAtMs = millis() + 500;       // give the HTTP answer time to leave
}

/** POST /api/restart   [PIN]. History is saved first (REQ-PERS-02). */
static void handleRestart() {
    touch();
    if (!requirePin()) return;
    sendOk();
    schedule(ACT_RESTART);
}

/** POST /api/factory-reset  (confirm=RESET)   [PIN]. Implements: REQ-PERS-06. */
static void handleFactoryReset() {
    touch();
    if (!requirePin()) return;
    if (s_server.arg("confirm") != "RESET") { sendError(400, "confirmation missing"); return; }
    sendOk();
    schedule(ACT_FACTORY_RESET);
}

